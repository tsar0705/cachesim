#!/usr/bin/env python3
"""Parameter sweeps over cachesim. Writes results/*.csv and results/SUMMARY.md.

Experiments
  1. size x associativity on naive vs. tiled 128x128 matrix multiply (L1 miss rate)
  2. replacement policy comparison on a looping working set slightly larger than the cache
  3. L1-only vs. L1+L2 AMAT on a hotspot workload
"""
import argparse
import csv
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tracegen  # noqa: E402


def write_trace(path, pattern, **kw):
    with open(path, "w") as f:
        for w, a in tracegen.generate(pattern, **kw):
            f.write(f"{'W' if w else 'R'} 0x{a:x}\n")


def run(binary, l1, trace, l2=None, extra=()):
    cmd = [binary, "--l1", l1] + (["--l2", l2] if l2 else []) + list(extra) + ["--raw", trace]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    kv = {k: int(v) for k, v in (l.split() for l in out.splitlines())}
    return kv


def miss_rate(kv, lvl="L1"):
    acc = kv[f"{lvl}.reads"] + kv[f"{lvl}.writes"]
    return (kv[f"{lvl}.read_misses"] + kv[f"{lvl}.write_misses"]) / acc if acc else 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin", default="build/cachesim")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    tmp = os.path.join(a.out, "tmp")
    os.makedirs(tmp, exist_ok=True)
    md = ["# cachesim sweep results\n", "Generated by `make sweep` (tools/sweep.py). All traces are seeded and reproducible.\n"]

    # 1. matmul naive vs tiled
    naive, tiled = os.path.join(tmp, "mm_naive.trace"), os.path.join(tmp, "mm_tiled.trace")
    write_trace(naive, "matmul", dim=128)
    write_trace(tiled, "matmul-blocked", dim=128, tile=16)
    rows = []
    for size_kb in (4, 8, 16, 32, 64):
        for assoc in (1, 2, 4, 8):
            for name, tr in (("naive", naive), ("tiled", tiled)):
                kv = run(a.bin, f"{size_kb}K:{assoc}:64:lru", tr)
                rows.append(dict(kernel=name, size_kb=size_kb, assoc=assoc, miss_rate=round(miss_rate(kv), 5),
                                 mem_reads=kv["mem.reads"], mem_writes=kv["mem.writes"]))
    with open(os.path.join(a.out, "matmul_size_assoc.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=rows[0].keys())
        w.writeheader()
        w.writerows(rows)
    md.append("\n## 1. 128x128 double matmul: naive vs. 16x16 tiled (L1 miss rate, 64 B blocks, LRU)\n")
    md.append("| size | assoc | naive | tiled | reduction |\n|---|---|---|---|---|")
    for size_kb in (4, 8, 16, 32, 64):
        for assoc in (1, 4):
            n = next(r for r in rows if r["kernel"] == "naive" and r["size_kb"] == size_kb and r["assoc"] == assoc)
            t = next(r for r in rows if r["kernel"] == "tiled" and r["size_kb"] == size_kb and r["assoc"] == assoc)
            red = (1 - t["miss_rate"] / n["miss_rate"]) * 100 if n["miss_rate"] else 0
            md.append(f"| {size_kb} KB | {assoc}-way | {n['miss_rate']:.4f} | {t['miss_rate']:.4f} | {red:.1f}% |")

    # 2. policies on loop slightly larger than cache (classic LRU/FIFO pathology) and hotspot
    loop, hot = os.path.join(tmp, "loop.trace"), os.path.join(tmp, "hot.trace")
    write_trace(loop, "loop", n=200000, seed=3, ws=9 * 1024, write_frac=0.2)
    write_trace(hot, "hotspot", n=200000, seed=4, hot=6 * 1024, span=1 << 20, p_hot=0.9, write_frac=0.2)
    prow = []
    for wl, tr in (("loop 9KB over 8KB cache", loop), ("hotspot 6KB hot set", hot)):
        for pol in ("lru", "fifo", "plru", "random"):
            kv = run(a.bin, f"8K:4:64:{pol}", tr)
            prow.append(dict(workload=wl, policy=pol, miss_rate=round(miss_rate(kv), 5), evictions=kv["L1.evictions"]))
    with open(os.path.join(a.out, "policies.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=prow[0].keys())
        w.writeheader()
        w.writerows(prow)
    md.append("\n## 2. Replacement policy (8 KB, 4-way, 64 B blocks)\n")
    md.append("| workload | policy | L1 miss rate | evictions |\n|---|---|---|---|")
    for r in prow:
        md.append(f"| {r['workload']} | {r['policy']} | {r['miss_rate']:.4f} | {r['evictions']} |")

    # 3. L2 effect on AMAT
    lat = (1, 10, 100)
    arow = []
    for label, l2 in (("L1 only", None), ("L1 + 256KB L2", "256K:8:64:lru")):
        cmd = [a.bin, "--l1", "8K:4:64:lru"] + (["--l2", l2] if l2 else []) + \
              ["--latency", f"{lat[0]},{lat[1]},{lat[2]}" if l2 else f"{lat[0]},{lat[2]}", hot]
        txt = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
        amat = float(next(l for l in txt.splitlines() if l.startswith("AMAT")).split()[1])
        arow.append(dict(config=label, amat_cycles=amat))
    with open(os.path.join(a.out, "amat.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=arow[0].keys())
        w.writeheader()
        w.writerows(arow)
    md.append("\n## 3. AMAT on hotspot trace (hit latencies 1 / 10 cycles, memory 100 cycles)\n")
    md.append("| config | AMAT (cycles) |\n|---|---|")
    for r in arow:
        md.append(f"| {r['config']} | {r['amat_cycles']:.2f} |")

    with open(os.path.join(a.out, "SUMMARY.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    for fn in os.listdir(tmp):
        os.remove(os.path.join(tmp, fn))
    os.rmdir(tmp)
    print("\n".join(md))


if __name__ == "__main__":
    main()
